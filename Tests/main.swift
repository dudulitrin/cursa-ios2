import Foundation

func check(_ condition: Bool, _ message: String) {
    guard condition else { fatalError(message) }
}
let valid = OfferParser.parse("lei 12.60 (NET, tax included)\n1 min • 0.4 km\n8 min • 3.4 km\nConfirm")
check(valid != nil, "Screenshot format")
check(abs(valid!.perKM - 3.3157894736842106) < 0.000001, "Total distance includes pickup")
let comma = OfferParser.parse("12,60 lei\n0,4 km\n3,4 km\nConfirmă")
check(comma == Offer(price: 12.60, pickup: 0.4, trip: 3.4), "Romanian comma and suffix currency")
check(OfferParser.parse("lei 12.60\n0.4 km\nConfirm") == nil, "Missing distance")
check(OfferParser.parse("lei 12.60\n0 km\n0 km\nConfirm") == nil, "Zero distance")
check(OfferParser.parse("lei 12.60\n0.4 km\n3.4 km") == nil, "Not an offer")
check(OfferParser.parse("lei 12.60\nlei 20\n0.4 km\n3.4 km\nConfirm") == nil, "Ambiguous price")
check(OfferParser.parse("lei 12.60\n0.4 km\n3.4 km\n5 km\nConfirm") == nil, "Ambiguous distances")
check(OfferParser.parse("12.60 lei\n1 min • 0.4 km\n8 min • 3.4 km\nConfirm") == valid, "Suffix currency followed by pickup minutes")
check(OfferParser.parse("RON 12,60\n0,4 km\n3,4 km\nConfirm") == comma, "RON prefix")
check(OfferParser.parse("12,60\u{00A0}lei\r\n0,4 km\r\n3,4 km\r\nConfirm") == comma, "Nonbreaking space and CRLF")
let matchOffer = OfferParser.parse("Bolt\nlei 11.46 (NET, tax included)\n2 min • 1 km\n9 min • 3.7 km\nMatch")
check(matchOffer == Offer(price: 11.46, pickup: 1, trip: 3.7, totalMinutes: 11), "Bolt Match offer")
check(abs(matchOffer!.perKM - 2.4382978723404256) < 0.000001, "Match total distance")
check(OfferParser.parse("lei 11.46\n1 km\n3.7 km\nMismatch") == nil, "Match must be a word")
check(valid?.totalMinutes == 9, "Pickup and trip minutes combined")
check(abs(valid!.perHour! - 84) < 0.000001, "Hourly rate includes pickup time")
check(abs(matchOffer!.perHour! - 62.50909090909091) < 0.000001, "Match hourly rate")
check(comma?.perHour == nil, "Missing time does not invent hourly rate")
check(OfferParser.parse("lei 12\n2 min 1 km\n3 km\nConfirm")?.totalMinutes == nil, "Incomplete time")
check(OfferParser.parse("lei 12\n2 min 1 km\n1 h 20 min 3 km\nConfirm")?.perHour == nil, "Hours not misread as minutes only")
check(OfferParser.parse("lei 12\n0 min 1 km\n0 min 3 km\nConfirm")?.perHour == nil, "Zero duration")
check(OfferParser.parse("lei 12\n2 min 1 km\n3 min 3 km\n4 min\nConfirm")?.perHour == nil, "Ambiguous duration")
let legacy = Data(#"{"price":12.6,"pickup":0.4,"trip":3.4}"#.utf8)
check((try? JSONDecoder().decode(Offer.self, from: legacy))?.totalMinutes == nil, "Old snapshot remains readable")
let morning = OfferParser.parse("lei 24.90\n1 min • 0.7 km\n17 min • 7.1 km\nConfirm")
check(morning != nil, "Morning screenshot recognized")
check(abs(morning!.totalDistance - 7.8) < 0.000001, "Morning distance")
check(abs(morning!.perKM - 24.9 / 7.8) < 0.000001, "Morning price per km")
check(abs(morning!.perHour! - 83) < 0.000001, "Morning hourly rate")
check(OfferParser.parse("lei 24.90\n1 min • 0.7 km\n17 min • 71 km\nConfirm") == nil, "Dropped trip decimal rejected")
check(OfferParser.parse("lei 24.90\n1 min • 7 km\n17 min • 7.1 km\nConfirm") == nil, "Dropped pickup decimal rejected")
check(OfferParser.parse("lei 100\n1 min • 0.7 km\n60 min • 71 km\nConfirm") != nil, "Real long trip retained")
